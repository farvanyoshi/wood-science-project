"""Compare every number hard-coded in the original paper with the values recomputed from data/raw.

Writes docs/VERIFICATION.md. Run from anywhere:  python analysis/verify_original.py
"""

import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
P = [3, 4, 5, 6, 7]

# Values exactly as they were typed into the original sections/data.typ and the appendix CSV tables.
ORIGINAL = {
    # (quantity in summary.csv, field): {level: value}
    ("segment_thickness_mm", "mean"): dict(zip(P, [24.4, 14.4, 14.5, 11.3, 14.4])),
    ("segment_thickness_mm", "se"): dict(zip(P, [1.14, 1.36, 1.13, 0.410, 1.36])),
    ("segment_width_mm", "mean"): dict(zip(P, [23.5, 30.4, 25.5, 22.8, 30.4])),
    ("segment_width_mm", "se"): dict(zip(P, [1.06, 0.210, 0.226, 0.234, 0.210])),
    ("segment_mass_g", "mean"): dict(zip(P, [15.2, 16.6, 17.6, 15.9, 18.4])),
    ("segment_mass_g", "se"): dict(zip(P, [0.798, 0.572, 1.365, 0.973, 1.481])),
    ("block_mass_g", "mean"): dict(zip(P, [85.7, 113.2, 100.4, 108.9, 91.0])),
    ("block_mass_g", "se"): dict(zip(P, [0.00935, 0.0131, 0.0179, 0.00987, 0.00766])),
    ("load_kn", "mean"): dict(zip(P, [9.81, 9.81, 7.85, 5.89, 9.81])),
    ("load_kn", "se"): dict(zip(P, [1.413, 0.942, 0.711, 1.285, 0.828])),
    ("density_g_cm3", "mean"): dict(zip(P, [0.273, 0.529, 0.596, 0.769, 0.544])),
    ("density_g_cm3", "se"): dict(zip(P, [0.0254, 0.012, 0.0129, 0.037, 0.0121])),
    ("mor_mpa", "mean"): dict(zip(P, [60.3, 186.0, 163.0, 213.0, 224.0])),
    ("mor_mpa", "se"): dict(zip(P, [11.8, 42.6, 24.5, 39.8, 22.6])),
    ("mor_mpa", "mean_excl"): dict(zip(P, [60.3, 137.0, 163.0, 213.0, 224.0])),
    ("mor_mpa", "se_excl"): dict(zip(P, [11.8, 18.5, 24.5, 39.8, 22.6])),
    ("sw_knm_per_kg", "mean"): dict(zip(P, [213, 344, 275, 266, 410])),
    ("sw_knm_per_kg", "se"): dict(zip(P, [29.3, 70.3, 42.1, 42.1, 39.7])),
    ("sw_knm_per_kg", "mean_excl"): dict(zip(P, [213, 264, 275, 266, 410])),
    ("sw_knm_per_kg", "se_excl"): dict(zip(P, [29.3, 35.2, 42.1, 42.1, 39.7])),
    ("impact_j", "mean"): {5: 5.90, 6: 4.00},
    ("impact_j", "se"): {5: 1.09, 6: 1.10},
}

FITS = {  # name: (slope, intercept) as printed in the paper
    "flexural_stiffness": (6.239, 1.852),
    "flexural_modulus": (5199, 28.58),
}

SPAN_CHANGED = {6, 7}  # paper used 70 mm, this repository uses the spreadsheet's 60 mm


def explain(quantity, field, level, rel):
    if abs(rel) < 0.01:
        return "matches (rounding)"
    if quantity in ("mor_mpa", "sw_knm_per_kg") and level in SPAN_CHANGED and field.startswith("mean"):
        return "span 60 mm (spreadsheet) instead of 70 mm: × 6/7"
    if field.startswith("se"):
        why = "original SE was not s/√n" if quantity != "load_kn" else "original SE was not s/√n (and used rounded loads)"
        if quantity in ("mor_mpa", "sw_knm_per_kg") and level in SPAN_CHANGED:
            why += "; span × 6/7"
        return why
    if quantity == "load_kn":
        return "original averaged tonnes rounded to 0.1 t before × 9.81"
    if quantity in ("segment_width_mm", "segment_mass_g", "segment_thickness_mm"):
        return "original hand-typed M row did not match its own data"
    return "**unexplained**"


def main():
    with open(REPO / "data/processed/summary.csv") as f:
        summary = {(r["quantity"], float(r["level"])): r for r in csv.DictReader(f)}
    with open(REPO / "data/processed/fits.csv") as f:
        fits = {r["name"]: r for r in csv.DictReader(f)}

    lines = []
    out = lines.append
    out("# Verification against the original paper\n")
    out("Generated by `analysis/verify_original.py` from `data/processed`. Each row compares a value that was")
    out("hand-typed in the original Typst sources (`sections/data.typ` and the appendix CSVs) with the value")
    out("now computed from `data/raw`. Rows within 1 % are reported as rounding matches.\n")

    counts = {"match": 0, "changed": 0, "unexplained": 0}
    out("## Summary statistics\n")
    out("| Quantity | Statistic | Pressure / time | Original | Recomputed | Δ | Explanation |")
    out("|---|---|---|---|---|---|---|")
    for (quantity, field), values in ORIGINAL.items():
        for level, old in values.items():
            new = float(summary[(quantity, float(level))][field])
            rel = (new - old) / old
            why = explain(quantity, field, level, rel)
            counts["match" if why.startswith("matches") else "unexplained" if "unexplained" in why else "changed"] += 1
            out(f"| `{quantity}` | {field} | {level} | {old:g} | {new:.4g} | {rel:+.1%} | {why} |")

    out("\n## Linear fits\n")
    out("| Fit | Original | Recomputed | R² |")
    out("|---|---|---|---|")
    for name, (m, b) in FITS.items():
        f = fits[name]
        out(f"| {name} | y = {m}x + {b} | y = {float(f['slope']):.4g}x + {float(f['intercept']):.4g} | {float(f['r2']):.4f} |")

    sw7 = float(summary[("sw_knm_per_kg", 7.0)]["mean"])
    mor7 = float(summary[("mor_mpa", 7.0)]["mean"])
    m3, m6 = (float(summary[("block_mass_g", p)]["mean"]) for p in (3.0, 6.0))
    out("\n## Numbers quoted in the prose\n")
    out("| Statement | Original | Now | Why |")
    out("|---|---|---|---|")
    out(f"| Peak mean strength-to-weight ratio (7 MPa) | 410 kN·m/kg | {sw7:.0f} kN·m/kg | 60 mm span |")
    out(f"| MOR gain over untreated pine (68 MPa) | “up to 3 times” | about {mor7 / 68:.1f}× | 60 mm span |")
    out(f"| 3 MPa block mass | 85.67 g | {m3:.2f} g | mean of the five weighings in the rough draft (85.67 g matches none of them) |")
    out(f"| 6 MPa block mass | 108.9 g | {m6:.2f} g | more precision |")
    out(f"| 6 MPa vs 3 MPa block mass | “about 25% more” | {100 * (m6 / m3 - 1):.0f}% | recomputed |")
    out(f"| 8 h impact energy | not reported | {float(summary[('impact_j', 8.0)]['mean']):.2f} J | added from the logbook |")

    out("\n## Other content changes\n")
    out("- The mass figure was labelled *kg*. It plots whole-block masses in **g** (rough draft Table 2).")
    out("- The load table was captioned in kN but listed metric tonnes. It now lists kN.")
    out("- The strength-to-weight table note said “millimeters”. It is kN·m/kg, and the S/W figures now use kN·m/kg (they used MN·m/kg before).")
    out("- The original `mor.csv` appendix table was malformed (shifted columns, no M/SE rows). It is regenerated.")
    out("- The impact discussion is qualified: 5–6 h dissolution had no clear effect, but 8 h dissolution reduced impact energy sharply.")
    out("- The duplicated draft paragraph in Methods (“adjustments for faster paper”) is removed.")
    out("- Appendix tables for block thickness and block mass are added. The Discussion's reference to “Table 2” now points to the block-mass table.")
    out("- The poster said the 7 MPa block had the lowest density and the MOR outlier was at 7 MPa. Both are corrected to match the paper (3 MPa and 4 MPa).")
    out("- The natural-wood control curves in `data/raw/curves` peak at 18.4 MPa, which does not reproduce the 68 MPa control MOR quoted in the paper. The 68 MPa is kept as a cited value (`lib/values.typ`).")

    out(f"\n**Totals:** {counts['match']} values match, {counts['changed']} changed with an identified cause, "
        f"{counts['unexplained']} unexplained.")
    path = REPO / "docs" / "VERIFICATION.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path.relative_to(REPO)}: {counts}")


if __name__ == "__main__":
    main()
